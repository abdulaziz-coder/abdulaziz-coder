import asyncio
from sqlalchemy import text

from .db import Base, engine
from .runtime import loop_factory
from .admin_auth import ensure_admin_account


async def main():
    async with engine.begin() as connection:
        await connection.run_sync(Base.metadata.create_all)
        # Additive, repeatable upgrade for local databases created before grade selection.
        await connection.execute(text(
            "ALTER TABLE enquiries ADD COLUMN IF NOT EXISTS grade INTEGER "
            "CONSTRAINT ck_enquiries_grade CHECK (grade BETWEEN 1 AND 11)"
        ))
        await connection.execute(text("ALTER TABLE enquiries ADD COLUMN IF NOT EXISTS reference_number BIGINT GENERATED BY DEFAULT AS IDENTITY"))
        await connection.execute(text("CREATE UNIQUE INDEX IF NOT EXISTS uq_enquiries_reference_number ON enquiries (reference_number)"))
        await connection.execute(text("ALTER TABLE enquiries ADD COLUMN IF NOT EXISTS staff_received_at TIMESTAMPTZ"))
        await connection.execute(text("ALTER TABLE enquiries ADD COLUMN IF NOT EXISTS phone VARCHAR(20)"))
    await engine.dispose()
    ensure_admin_account()
    print("Local admissions database initialized.")


if __name__ == "__main__":
    asyncio.run(main(), loop_factory=loop_factory)
